# 전화번호 비교할 때 사용할 함수
def normalize(number: str) -> str:
    """번호에서 숫자 이외의 문자(하이픈 등)를 전부 제거"""
    return re.sub(r'\D', '', number)


def classify_number_type(number: str) -> str:
    """번호를 카테고리로 분류 (마스터표 원 정의 기반: 010/070/02/00X/050 + 특번)"""
    n = normalize(number)
    if n.startswith('010'):
        return '010'
    elif re.match(r'^1[5-8]\d{2}', n):      # 1544/1566/1588/1600/1661/1670/1800 등
        return '특번'
    elif n.startswith('02'):
        return '02(유선)'
    elif n.startswith('070'):
        return '070(인터넷전화)'
    elif n.startswith('00'):
        return '00X(국제)'
    else:
        return '기타' # 지역 번호 포함


